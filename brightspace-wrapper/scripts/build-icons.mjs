// Regenerates src/icons.js from the Material Symbols (Rounded, weight 400) SVG set.
// Usage: npm i @material-symbols/svg-400 && node scripts/build-icons.mjs <path-to-node_modules>
import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2] || 'node_modules';
const dir = path.join(root, '@material-symbols/svg-400/rounded');
const names = [
  'menu','check','search','home','school','checklist','calendar_month','grading','star','settings','light_mode','dark_mode',
  'open_in_new','campaign','folder','description','picture_as_pdf','link','play_circle','quiz','assignment',
  'forum','groups','keyboard_arrow_down','chevron_right','chevron_left','arrow_back','close','keep','refresh',
  'attach_file','check_circle','schedule','error','event','slideshow','palette','more_vert','download',
  'inbox','visibility_off','visibility','filter_list','done_all','notifications','article','folder_open',
  'history','unfold_more','unfold_less','swap_horiz','login','task_alt','radio_button_unchecked','lock',
  'table_chart','image','auto_stories','today','info','wifi_off','tune','view_agenda','grid_view','videocam',
  'add','delete','content_copy','upload_file','person','send','logout','edit','archive'
];
const out = {};
for (const n of names) {
  for (const file of [`${n}.svg`, `${n}-fill.svg`]) {
    const p = path.join(dir, file);
    if (!fs.existsSync(p)) continue;
    const svg = fs.readFileSync(p, 'utf8');
    const d = [...svg.matchAll(/ d="([^"]+)"/g)].map(m => m[1]).join(' ');
    out[file.replace('.svg', '')] = d;
  }
  if (!out[n]) console.warn('missing', n);
}
const js = `/* Generated by scripts/build-icons.mjs from Material Symbols Rounded (Apache-2.0). */\n` +
  `(window.Lumen = window.Lumen || {}).ICONS = ${JSON.stringify(out)};\n`;
fs.writeFileSync(new URL('../src/icons.js', import.meta.url), js);
console.log('wrote', Object.keys(out).length, 'icons,', js.length, 'bytes');
